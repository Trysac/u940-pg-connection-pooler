/// Computes the 16-byte RFC 1321 MD5 digest of `data`.
#[allow(clippy::many_single_char_names)]
#[must_use]
pub fn md5_bytes(data: &[u8]) -> [u8; 16] {
    let mut a0: u32 = 0x6745_2301;
    let mut b0: u32 = 0xefcd_ab89;
    let mut c0: u32 = 0x98ba_dcfe;
    let mut d0: u32 = 0x1032_5476;

    let bit_len = (data.len() as u64).wrapping_mul(8);
    let mut padded = Vec::with_capacity((data.len() + 72) & !63);
    padded.extend_from_slice(data);
    padded.push(0x80);
    while padded.len() % 64 != 56 {
        padded.push(0);
    }
    padded.extend_from_slice(&bit_len.to_le_bytes());

    for chunk in padded.as_chunks::<64>().0 {
        let mut m = [0u32; 16];
        for (i, word) in m.iter_mut().enumerate() {
            let base = i * 4;
            *word = u32::from_le_bytes([
                chunk[base],
                chunk[base + 1],
                chunk[base + 2],
                chunk[base + 3],
            ]);
        }

        let mut a = a0;
        let mut b = b0;
        let mut c = c0;
        let mut d = d0;

        for i in 0..64 {
            let (f, g) = match i {
                0..=15 => ((b & c) | (!b & d), i),
                16..=31 => ((d & b) | (!d & c), (5 * i + 1) % 16),
                32..=47 => (b ^ c ^ d, (3 * i + 5) % 16),
                _ => (c ^ (b | !d), (7 * i) % 16),
            };
            let temp = d;
            d = c;
            c = b;
            let sum = a.wrapping_add(f).wrapping_add(K[i]).wrapping_add(m[g]);
            b = b.wrapping_add(sum.rotate_left(S[i]));
            a = temp;
        }

        a0 = a0.wrapping_add(a);
        b0 = b0.wrapping_add(b);
        c0 = c0.wrapping_add(c);
        d0 = d0.wrapping_add(d);
    }

    let mut out = [0u8; 16];
    out[0..4].copy_from_slice(&a0.to_le_bytes());
    out[4..8].copy_from_slice(&b0.to_le_bytes());
    out[8..12].copy_from_slice(&c0.to_le_bytes());
    out[12..16].copy_from_slice(&d0.to_le_bytes());
    out
}

/// Computes the lowercase hex RFC 1321 MD5 digest of `data`.
#[must_use]
pub fn md5_hex(data: &[u8]) -> String {
    let digest = md5_bytes(data);
    let mut hex = String::with_capacity(32);
    for b in digest {
        let _ = write!(hex, "{b:02x}");
    }
    hex
}

/// Computes the PostgreSQL `MD5Password` response string for `user`, `password`, and `salt`.
///
/// Per PostgreSQL protocol section 55.3, the formula is
/// `"md5" + md5(md5(password + user) + salt)`.
#[must_use]
pub fn md5_password(user: &str, password: &str, salt: [u8; 4]) -> String {
    let mut inner = Vec::with_capacity(password.len() + user.len());
    inner.extend_from_slice(password.as_bytes());
    inner.extend_from_slice(user.as_bytes());
    let inner_hex = md5_hex(&inner);

    let mut outer = Vec::with_capacity(36);
    outer.extend_from_slice(inner_hex.as_bytes());
    outer.extend_from_slice(&salt);
    let outer_hex = md5_hex(&outer);

    let mut result = String::with_capacity(35);
    result.push_str("md5");
    result.push_str(&outer_hex);
    result
}
